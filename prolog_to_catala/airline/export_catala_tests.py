"""Regenerate protected airline tests with answers from the original Prolog programs.

The independent programs use different fact schemas, so factual itineraries are
read through the existing corpus-text adapter. Each itinerary is checked against
the shared Prolog oracle and its own original program before it is emitted.
Neither test inputs nor expected answers depend on a candidate Catala program.
"""
from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor
from decimal import Decimal
import hashlib
from pathlib import Path
import re
import subprocess
import tempfile

from .airlinelib import airline, corpus, paths

DESTINATION = paths.ROOT / "data/catala_gold/airline/tests_catala/AirlineCases.catala_en"
TOTAL = re.compile(r"Total cost:\s*(\d+(?:\.\d+)?)", re.IGNORECASE)


def reference_total(trip: corpus.Trip) -> int:
    source = paths.AIRLINE_RAW / "cases" / f"{trip.id}.pl"
    result = subprocess.run(
        [str(paths.SWIPL), "-q", "-f", str(source)],
        capture_output=True, text=True, timeout=60, stdin=subprocess.DEVNULL,
    )
    totals = TOTAL.findall(result.stdout)
    if result.returncode or len(totals) != 1:
        raise ValueError(
            f"{trip.id}: original Prolog did not produce one total: "
            f"{result.stdout}\n{result.stderr}"
        )
    total = Decimal(totals[0])
    if total != trip.label:
        raise ValueError(f"{trip.id}: Prolog total {total} differs from label {trip.label}")
    # Check that the normalized factual input still reproduces the original
    # answer in Prolog; do not use the Catala implementation as an oracle.
    with tempfile.TemporaryDirectory(prefix="airline-test-export-") as directory:
        normalized = Path(directory) / "case.pl"
        normalized.write_text(airline.render_prolog(trip))
        oracle = airline.run_prolog(normalized)
    if oracle["rc"] or oracle["total"] != total or oracle["accepted"] is not True:
        raise ValueError(f"{trip.id}: normalized Prolog itinerary disagrees: {oracle}")
    return int(total)


def render_itinerary(trip: corpus.Trip) -> str:
    items = ";\n      ".join(
        f"W.Item {{ -- kind: W.ItemKind.{corpus.ITEM_KINDS[item.kind]} "
        f"-- length: {item.length} -- width: {item.width} "
        f"-- height: {item.height} -- weight: {item.weight} }}"
        for item in trip.items
    )
    return "\n".join([
        "W.Itinerary {",
        f"    -- origin: W.City.{corpus.city_catala(trip.origin)}",
        f"    -- destination: W.City.{corpus.city_catala(trip.destination)}",
        f"    -- cabin: W.Cabin.{corpus.CABIN_CATALA[trip.cabin]}",
        f"    -- ticket: ${trip.ticket}",
        f"    -- items: [{items}]",
        f"    -- status_at_ticketing: W.EliteStatus.{corpus.STATUSES[trip.status_at_ticketing]}",
        f"    -- status_at_checkin: W.EliteStatus.{corpus.STATUSES[trip.status_at_checkin]}",
        f"    -- cardmember: {str(trip.cardmember).lower()}",
        f"    -- military: W.MilitaryStatus.{corpus.MILITARY[trip.military]}",
        f"    -- flagship: {str(trip.flagship).lower()}",
        f"    -- children: {trip.children}",
        "  }",
    ])


def generate(jobs: int = 8) -> str:
    trips = corpus.load_airline()
    originals = {source.stem for source in (paths.AIRLINE_RAW / "cases").glob("*.pl")}
    if {trip.id for trip in trips} != originals:
        raise ValueError("Airline metadata differs from the original Prolog case inventory")
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        totals = list(pool.map(reference_total, trips))
    lines = [
        "# Generated by python3 -m prolog_to_catala.airline.export_catala_tests.",
        "# Inputs use the corpus-text adapter, checked against the shared Prolog oracle.",
        "# Expected totals are executed from each original Prolog program and checked against its label.",
        "> Module AirlineCases", "> Using Api as A", "> Using Definitions as W",
        "", "```catala-metadata",
    ]
    for trip in trips:
        lines += ["#[test]", f"declaration scope Test{trip.id}:",
                  "  result scope A.TotalCost", ""]
    lines += ["```", "", "```catala"]
    for trip, total in zip(trips, totals):
        source = paths.AIRLINE_RAW / "cases" / f"{trip.id}.pl"
        lines += [
            f"# Prolog source: data/prolog/airline/cases/{source.name}",
            f"# SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}",
            f"scope Test{trip.id}:",
            "  definition result.itinerary equals " + render_itinerary(trip),
            f"  assertion result.total_cost = (money of {total})", "",
        ]
    return "\n".join(lines + ["```", ""])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DESTINATION)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--jobs", type=int, default=8)
    args = parser.parse_args()
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    source = generate(args.jobs)
    if args.check:
        if not args.output.is_file() or args.output.read_text() != source:
            raise SystemExit("Generated airline tests are stale")
        print("Protected airline tests match the original Prolog programs")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(source)
        print(args.output)


if __name__ == "__main__":
    main()
