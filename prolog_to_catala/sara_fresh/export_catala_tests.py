"""Regenerate protected SARA cases through the validated normalization adapter."""
from __future__ import annotations
import argparse
from copy import deepcopy
import json
import hashlib
from pathlib import Path
import re
from .literals import render_literal
from .normalization import normalize_world
ROOT=Path(__file__).resolve().parents[2]
FIXTURES=ROOT/'data/catala_gold/sara/legacy_inputs.json'
DESTINATION=ROOT/'data/catala_gold/sara/tests_catala/SaraTaxCases.catala_en'


def load_cases():
    fixtures=json.loads(FIXTURES.read_text())
    originals={'TestTaxCase'+source.stem.removeprefix('tax_case_') for source in (ROOT/'data/prolog/sara/cases').glob('tax_case_*.pl')}
    if set(fixtures['cases']) != originals:
        raise ValueError('Legacy fixture cases differ from the original Prolog tax-case inventory')
    for name,record in fixtures['cases'].items():
        record=deepcopy(record);world={}
        # The versioned fixtures are legacy sparse records, not public inputs.
        # Expand row defaults, then migrate all active facts to lists.
        for slot, value in record['world'].items():
            family=slot.split('_',1)[0]
            world[slot]=deepcopy(value) if family=='dependency' else {
                **deepcopy(fixtures['defaults'][family]), **value}
        normalized=normalize_world(world)
        source=ROOT/'data/prolog/sara/cases'/('tax_case_'+name.removeprefix('TestTaxCase')+'.pl')
        if hashlib.sha256(source.read_bytes()).hexdigest() != record['source_sha256']:
            raise ValueError(f'{name}: original Prolog source changed; review legacy factual fixture')
        goal=re.search(r':- tax\(([^,]+),(\d+),(\d+)\)',source.read_text())
        if not goal or goal[1] != record['prolog_subject'] or goal[3] != str(record['expected']) or int(goal[2]) != record['period']['tax_year']:
            raise ValueError(f'{name}: fixture differs from original Prolog expectation/year')
        record['world']=normalized['world']
        yield name,record,normalized


def generate():
    cases=list(load_cases())
    lines=['# Generated by python3 -m prolog_to_catala.sara_fresh.export_catala_tests.',
           '# Legacy factual fixtures are migrated to lists, normalized, and validated before rendering.',
           '# Expected amounts are checked against original Prolog tax/3 claims.',
           '> Module SaraTaxCases','> Using Api as A','> Using Definitions as W','','```catala-metadata']
    for name,_,_ in cases:lines += ['#[test]',f'declaration scope {name}:','  result scope A.TotalTax','']
    lines += ['```','','```catala']
    for name,record,_ in cases:
        lines += [f'scope {name}:']
        for field,typ in [('world','World'),('taxpayer','Entity'),('period','TaxPeriod')]:
            lines.append(f'  definition result.{field} equals '+render_literal(typ,record[field]))
        lines += [f'  assertion result.total_tax = (money of {record["expected"]})','']
    return '\n'.join(lines+['```',''])


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--output',type=Path,default=DESTINATION);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    source=generate()
    if args.check:
        if args.output.read_text()!=source:raise SystemExit('Generated SARA tests are stale')
        print('Protected SARA tests match validated fixtures')
    else:
        args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text(source);print(args.output)
if __name__=='__main__':main()
