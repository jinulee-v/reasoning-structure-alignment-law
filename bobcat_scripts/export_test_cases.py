#!/usr/bin/env python3
"""Publish already-generated BOBCat cases for RTDF verification.

This is intentionally separate from ``rtdf_formalizer.experiment``: validation
consumes a frozen corpus and never invokes BOBCat or changes that corpus.
"""
from __future__ import annotations

import argparse
import json
import shutil
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
PORT_OUTPUT = ROOT / ".port"
GOLD_ROOT = ROOT / "data/catala_gold"
PROJECT_NAMES = {"nsw_community_gaming": "NSW_community_gaming"}


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser(description=__doc__)
    result.add_argument("--port", action="append", dest="ports", required=True)
    return result


def publish(port: str) -> dict[str, object]:
    source_name = "dataset"
    source = PORT_OUTPUT / f"{port}_bobcat" / source_name
    if not source.is_dir():
        raise SystemExit(
            f"missing generated BOBCat dataset: {source}\n"
            "run bobcat_scripts/generate_dataset.py first"
        )
    destination = GOLD_ROOT / PROJECT_NAMES.get(port, port) / "tests_bobcat"
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(
        prefix=f".{port}.", dir=destination.parent
    ) as temporary_name:
        staged = Path(temporary_name) / port
        staged.mkdir()
        index_path = source / "INDEX.json"
        index = json.loads(index_path.read_text(encoding="utf-8"))
        case_files = sorted(
            {
                entry["file"]
                for entry in index.get("targets", [])
                if isinstance(entry, dict) and isinstance(entry.get("file"), str)
            }
        )
        for name in ("INDEX.json", *case_files):
            candidate = source / name
            if not candidate.is_file():
                raise SystemExit(f"BOBCat index references missing file: {candidate}")
            shutil.copy2(candidate, staged / name)
        (staged / "README.md").write_text(
            f"# BOBCat {port} tests\n\n"
            "Frozen public wrapper cases generated by "
            "`bobcat_scripts/generate_dataset.py`. See `INDEX.json` for the "
            "compiler version and per-target results.\n",
            encoding="utf-8",
        )
        wrappers = PORT_OUTPUT / f"{port}_bobcat" / "generated"
        if wrappers.is_dir():
            shutil.copytree(wrappers, staged / "wrappers")
        previous = destination.with_name(f".{port}.previous")
        if previous.exists():
            shutil.rmtree(previous)
        if destination.exists():
            destination.rename(previous)
        staged.rename(destination)
        if previous.exists():
            shutil.rmtree(previous)
    files = sorted(path.name for path in destination.iterdir() if path.is_file())
    return {"port": port, "source": source_name, "destination": str(destination), "files": files}


def main() -> int:
    args = parser().parse_args()
    records = [publish(port) for port in sorted(set(args.ports))]
    print(json.dumps(records, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
